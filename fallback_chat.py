"""Separately scored product: learned CPU call/slot head plus the supplied neural student."""
from dataclasses import asdict, dataclass
import json
import re

import torch

from dialogue import parse_assistant
from fallback_head import load_head
from guards import ResourceStop
from local_chat import NO_CALL, encode_frame, tool_view
from tokenizer import EOT
from tools import FixtureSession


PLAIN = "\nReply with the reported number only.\nAnswer:"


@dataclass
class Reply:
    raw: str
    answer: str | None
    failure: str | None
    suffix: list[int]
    origin: str


class Chat:
    """The head chooses calls; every user-visible answer is generated by the supplied GPT-2."""
    def __init__(self, model, tok, guard, head=None):
        self.model, self.tok, self.guard = model, tok, guard
        self.head = head if head is not None else load_head()
        self.session = FixtureSession()
        self.ids = []
        self.history = []

    def decide(self, user):
        """Composable structured decision, using only the broker's actual prior trace."""
        return self.head.decide(user, self.session.trace)

    @torch.inference_mode()
    def greedy(self, ids, cap):
        if len(ids)+cap > self.model.positions.num_embeddings:
            raise ValueError("conversation exceeds model context")
        generated = []
        device = next(self.model.parameters()).device
        for _ in range(cap):
            self.guard.check()
            row = torch.tensor([ids+generated], device=device)
            token = self.model(row)[0,-1].argmax().item()
            generated.append(token)
            if token == EOT:
                break
        raw = self.tok.decode([token for token in generated if token != EOT])
        return raw, generated

    def respond_ordinary(self, user, history_ids):
        """Produce an ordinary answer from exact exchange history; no adapter can run here."""
        prefix = self.tok.encode("Assistant:").ids
        raw, suffix = self.greedy(history_ids+prefix, 96)
        try:
            payload = parse_assistant(self.tok, suffix)
            if "text" not in payload:
                raise ValueError("student proposed a call outside the learned route")
            return Reply(raw, payload["text"], None, prefix+suffix, "gpt2/dialogue")
        except ValueError as error:
            return Reply(raw,None,str(error),prefix+suffix,"gpt2/dialogue")

    def respond_number(self, record):
        """Project the actual observed value into the previously tested plain-copy prompt."""
        value = record["data"]["result"]
        number = str(int(value)) if type(value) is float and value.is_integer() else str(value)
        prompt = f"The {record['name']} tool returned {number}." + PLAIN
        raw, suffix = self.greedy(self.tok.encode(prompt).ids, 16)
        if suffix[-1] != EOT or not re.fullmatch(r"[+-]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?", raw.strip()):
            reason = "numeric reply reached token limit" if suffix[-1] != EOT else "student emitted a nonnumeric reply"
            attempted = self.tok.encode("Assistant:").ids + suffix
            reply = Reply(raw, None, reason, attempted, "gpt2/observed-number")
        else:
            # Keep wrong generations visible. No host substitution with the expected value.
            value = raw.strip()
            prefix, body = encode_frame(self.tok, "assistant", {"text":value})
            reply = Reply(raw, value, None, prefix+body, "gpt2/observed-number")
        return reply,prompt

    @torch.inference_mode()
    def turn(self, user, permit_calls=True, fixture_for=None, fixture=None):
        permit = permit_calls is True and not bool(NO_CALL.search(user))
        self.session.start_turn(permit_calls=permit, fixture_for=fixture_for, fixture=fixture)
        offset = len(self.session.trace)
        working = self.ids.copy()
        prefix,body = encode_frame(self.tok,"user",user)
        working.extend(prefix+body)
        result = dict(answer=None, frames=[], frame_origins=[], failure=None, trace=[],
                      decision=None, selected_path=None, copy_prompt=None)
        try:
            self.guard.check()
            if len(working)+96 > self.model.positions.num_embeddings:
                raise ValueError("conversation exceeds model context")
            decision = self.decide(user)
            result["decision"] = asdict(decision)
            observed = None
            if decision.proposal is not None and permit:
                proposal = decision.proposal
                prefix,body = encode_frame(self.tok,"assistant",{"call":proposal})
                working.extend(prefix+body)
                result["frames"].append(self.tok.decode(body[:-1]))
                result["frame_origins"].append("learned-head/typed-serialization")
                if len(working)+96 > self.model.positions.num_embeddings:
                    raise ValueError("insufficient context for a tool turn")
                event = self.session.propose(json.dumps(proposal), assistant_call_boundary=True)
                prefix,body = encode_frame(self.tok,"tool",tool_view(event))
                working.extend(prefix+body)
                if event["ok"]:
                    observed = event
            elif decision.action == "recall_number":
                last = self.session.trace[-1] if self.session.trace else None
                if last and last["ok"]:
                    observed = last
            if observed is not None:
                reply,result["copy_prompt"] = self.respond_number(observed)
            else:
                reply = self.respond_ordinary(user, working)
            result["selected_path"] = reply.origin
            result["frame_origins"].append(reply.origin)
            result["frames"].append(reply.raw)
            result["answer"],result["failure"] = reply.answer,reply.failure
            working.extend(reply.suffix)
        except (ValueError, RuntimeError, ResourceStop, RecursionError) as error:
            result["failure"] = str(error)
        finally:
            result["trace"] = self.session.trace[offset:]
            if len(working)<=self.model.positions.num_embeddings or result["trace"]:
                if working and working[-1]!=EOT:
                    working.append(EOT)
                self.ids = working
            self.history.append(dict(user=user, permit_calls=permit, **result))
        return result
